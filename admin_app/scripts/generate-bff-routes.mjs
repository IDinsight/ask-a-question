/**
 * Generate src/lib/bff/routes.gen.ts from openapi.json.
 *
 * The output is the BFF's allowlist: every "METHOD /path/{param}" the admin app
 * may proxy to core_backend, with a RegExp to match concrete paths. The proxy
 * also logs the matched template (e.g. "/user/{username}") instead of the real
 * path, so path parameters such as usernames never reach the logs.
 *
 * Runs as part of `pnpm api:generate`, after openapi-ts, from the same spec and
 * the same exclusion list (scripts/api-scope.mjs).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { isExcluded } from "./api-scope.mjs";

const root = resolve(import.meta.dirname, "..");
const spec = JSON.parse(readFileSync(resolve(root, "openapi.json"), "utf8"));
const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete", "head"]);

/** "/content/{content_id}" -> "^/content/[^/]+$" (one segment per param). */
const toRegExpSource = (template) =>
  "^" +
  template
    .split(/\{[^}]+\}/)
    .map((literal) => literal.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("[^/]+") +
  "$";

const routes = [];
for (const [template, pathItem] of Object.entries(spec.paths)) {
  for (const method of Object.keys(pathItem)) {
    if (!HTTP_METHODS.has(method) || isExcluded(method, template)) continue;
    routes.push({ method: method.toUpperCase(), template });
  }
}
// Static segments before params, so "/user/current-user" wins over "/user/{username}".
routes.sort(
  (a, b) =>
    a.template.split("{").length - b.template.split("{").length ||
    a.template.localeCompare(b.template) ||
    a.method.localeCompare(b.method),
);

const lines = routes.map(
  ({ method, template }) =>
    `  { method: "${method}", template: "${template}", pattern: /${toRegExpSource(
      template,
    ).replace(/\//g, "\\/")}/ },`,
);

writeFileSync(
  resolve(root, "src/lib/bff/routes.gen.ts"),
  `// This file is auto-generated by scripts/generate-bff-routes.mjs. Do not edit.
// Source: openapi.json (core_backend), minus scripts/api-scope.mjs exclusions.

export interface BffRoute {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE" | "HEAD";
  /** OpenAPI path template, e.g. "/content/{content_id}". Safe to log. */
  template: string;
  /** Matches a concrete backend path (no query string). */
  pattern: RegExp;
}

export const BFF_ROUTES: readonly BffRoute[] = [
${lines.join("\n")}
];
`,
);
console.log(`Wrote ${routes.length} BFF routes to src/lib/bff/routes.gen.ts`);
